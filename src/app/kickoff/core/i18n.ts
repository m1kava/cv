const DICTS = { en: EN, ka: KA };

/**
 * Tiny signal-based i18n. `t()` reads the language signal, so any template
 * calling it re-renders when the language changes — no pipes, no reloads.
 */
@Injectable()
export class I18n {
  private readonly settings = inject(SettingsStore);

  readonly t = (key: string, params?: Record<string, string | number>): string => {
    let text = DICTS[this.settings.lang()][key] ?? EN[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) text = text.replace(`{${k}}`, String(v));
    return text;
  };
}
